-- Local/disposable runtime contract for the narrow AVA completion reader.
-- Run only against a local/staging baseline that already contains the teacher
-- availability submission contract. The enclosing rollback prevents fixture
-- rows or the forward migration from persisting.

begin;

-- `ileaudit` intentionally contains only a lightweight schema. Build the
-- exact reader prerequisites inside this rollback-only transaction so this
-- contract does not depend on unrelated availability migrations being loaded.
create schema if not exists internal;

create table if not exists public.teacher_availability_submissions (
  id bigint generated by default as identity primary key,
  teacher_id text not null,
  teacher_name text not null,
  submission_month text not null,
  availability_timezone text not null,
  current_city text,
  additional_students integer not null default 0,
  availability_slots jsonb not null default '[]'::jsonb,
  notes text,
  status text not null default 'pending' check (status in ('pending', 'approved', 'rejected')),
  submitted_at timestamptz not null default now(),
  reviewed_at timestamptz,
  reviewed_by text,
  review_note text,
  check (
    (status = 'pending' and reviewed_at is null and reviewed_by is null)
    or (status in ('approved', 'rejected') and reviewed_at is not null and nullif(trim(reviewed_by), '') is not null)
  )
);

alter table public.teacher_availability_submissions enable row level security;
revoke all on table public.teacher_availability_submissions from public, anon, authenticated;

create or replace function internal.verify_ops_secret(p_secret text)
returns boolean
language sql
stable
set search_path = ''
as $$
  select p_secret = 'ava-completion-reader-fixture-secret';
$$;

