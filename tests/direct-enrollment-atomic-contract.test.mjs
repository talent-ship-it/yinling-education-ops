import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import test from "node:test";

const root = path.resolve(import.meta.dirname, "..");
const migration = fs.readFileSync(path.join(root, "supabase/migrations/20260819101300_student_direct_enrollment_atomic.sql"), "utf8");
const route = fs.readFileSync(path.join(root, "app/api/operations/direct-enrollment/route.ts"), "utf8");
const client = fs.readFileSync(path.join(root, "app/operations-client.tsx"), "utf8");

test("direct enrollment migration is secret-gated, replay-first, and fixed-lock ordered", () => {
  assert.match(migration, /verify_ops_secret\(p_secret\)/);
  assert.match(migration, /where entity = 'students' for update/);
  assert.match(migration, /where entity = 'lpItems' for update/);
  assert.match(migration, /where entity = 'tasks' for update/);
  assert.ok(migration.indexOf("select * into prior") < migration.indexOf("version_conflict"));
  assert.match(migration, /command_intent is distinct from p_command_intent/);
  assert.match(migration, /direct_enrollment_intent_mismatch/);
  assert.match(migration, /subject_not_available/);
  assert.match(migration, /student_archived/);
  assert.match(migration, /update public\.ops_state set payload = next_students/);
  assert.match(migration, /update public\.ops_state set payload = next_lp_items/);
  assert.match(migration, /update public\.ops_state set payload = next_tasks/);
  assert.match(migration, /bookings_state public\.ops_state%rowtype/);
  assert.match(migration, /where entity = 'bookings' for share/);
  assert.match(migration, /teacherSubjectId/);
  assert.match(migration, /case when students_state\.entity is null then null::public\.ops_state/);
  assert.match(migration, /direct_enrollment_package_payload_mismatch/);
  assert.match(migration, /direct_enrollment_lp_item_payload_mismatch/);
  assert.match(migration, /direct_enrollment_task_payload_mismatch/);
  assert.match(migration, /direct_enrollment_task_ids_mismatch/);
  assert.match(migration, /content_due_at/);
  assert.match(migration, /'handover'/);
  assert.match(migration, /'specified-content'/);
  assert.match(migration, /'preparation-follow-up'/);
  assert.match(migration, /'ruleKey', 'lp\.' \|\| rule/);
  assert.match(migration, /round\(round\(package_total, 6\) - round\(consumed_hours, 6\), 6\) <> 0/);
  const atomicStart = migration.indexOf("create or replace function public.create_student_direct_enrollment_atomic");
  const atomicReplay = migration.indexOf("select * into prior", atomicStart);
  const atomicStudentLock = migration.indexOf("select * into students_state", atomicStart);
  const atomicVersionCheck = migration.indexOf("message = 'version_conflict'", atomicStart);
  assert.ok(atomicReplay > atomicStart && atomicReplay < atomicStudentLock, "atomic replay must precede row locks");
  assert.ok(atomicReplay < atomicVersionCheck, "atomic replay must precede OCC");
});

test("route has no distributed-write fallback and client applies all three rows", () => {
  assert.match(route, /DIRECT_ENROLLMENT_ATOMIC_RPC/);
  assert.match(route, /direct_enrollment_contract_unavailable/);
  assert.match(route, /getStudentDirectEnrollmentCommandResult/);
  assert.match(client, /studentsShared\.applyRemote\(body\.studentsRow/);
  assert.match(client, /lpShared\.applyRemote\(body\.lpItemsRow/);
  assert.match(client, /tasksShared\.applyRemote\(body\.tasksRow/);
  assert.match(client, /共享状态行暂不可用，请刷新后安全重试/);
  assert.match(client, /readDirectEnrollmentPendingCommands/);
  assert.match(client, /persistDirectEnrollmentPendingCommands/);
  assert.match(client, /clearDirectEnrollmentPendingCommands/);
  assert.match(client, /upsertDirectEnrollmentPendingCommand/);
  assert.match(client, /response\.status === 409/);
  assert.match(client, /lpDraftType === "学生直报（无试听）"/);
  assert.match(client, /readableScopedBookings/);
  const directStart = client.indexOf("if (workflowType === \"学生直报（无试听）\")");
  const directEnd = client.indexOf("const submitLpRevision", directStart);
  const direct = client.slice(directStart, directEnd < 0 ? undefined : directEnd);
  assert.ok(direct.indexOf("setStudents((current)") === -1 || direct.indexOf("return;") < direct.indexOf("setStudents((current)"));
  assert.equal(direct.includes("createStudentLessonPackage"), false, "direct branch must not build packages in the browser");
  const replayCall = route.indexOf("const replay = await getStudentDirectEnrollmentCommandResult");
  const stateRead = route.indexOf("const rows = await getOpsState");
  const scopeCheck = route.indexOf("canOperateStudent(access, command.studentId)");
  assert.ok(replayCall >= 0 && replayCall < stateRead && replayCall < scopeCheck, "route replay must precede current scope/state checks");
  assert.match(route, /students_row/);
  assert.match(route, /lp_items_row/);
  assert.match(route, /tasks_row/);
  assert.match(route, /subject_package_has_balance/);
  assert.match(route, /code: "subject_package_has_balance"/);
  assert.match(route, /return noStore\(\{ error: "该科目已有未用完的课包余额/);
});
