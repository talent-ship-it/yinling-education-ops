function withOriginalWhitespace(source: string, translated: string) {
  const leading = source.match(/^\s*/)?.[0] ?? "";
  const trailing = source.match(/\s*$/)?.[0] ?? "";
  return `${leading}${translated}${trailing}`;
}

export function translateInterfaceText(value: string, language: InterfaceLanguage) {
  if (language !== "en-AU" || !/[一-龯]/.test(value)) return value;
  const trimmed = value.trim();
  if (!trimmed) return value;
  const normalized = trimmed.replace(/\s+/g, " ");

  const direct = englishInterfacePhrases[trimmed]
    ?? englishInterfacePhrases[normalized]
    ?? englishInterfaceFragments[trimmed]
    ?? englishInterfaceFragments[normalized]
    ?? displayTerm(normalized, language);
  if (direct !== normalized) return withOriginalWhitespace(value, direct);

  for (const [pattern, formatter] of dynamicTranslations) {
    const match = normalized.match(pattern);
    if (match) return withOriginalWhitespace(value, formatter(...match));
  }

  let translated = normalized;
  for (const [source, replacement] of inlineTranslations) translated = translated.replaceAll(source, replacement);
  return translated === normalized ? value : withOriginalWhitespace(value, translated);
}

const translatedAttributes = ["aria-label", "title", "placeholder"] as const;

export function observeInterfaceLocalization(root: HTMLElement, language: InterfaceLanguage) {
  type TranslationState = { source: string; translated: string };
  const textState = new Map<Text, TranslationState>();
  const attributeState = new Map<Element, Map<string, TranslationState>>();

  const translateTextNode = (node: Text) => {
    const parent = node.parentElement;
    if (!parent || parent.closest("script, style, [data-preserve-language='true']")) return;
    const current = node.nodeValue ?? "";
    const previous = textState.get(node);
    const source = previous && current === previous.translated ? previous.source : current;
    const translated = translateInterfaceText(source, language);
    textState.set(node, { source, translated });
    if (current !== translated) node.nodeValue = translated;
  };

  const translateElementAttributes = (element: Element) => {
    let states = attributeState.get(element);
    if (!states) {
      states = new Map();
      attributeState.set(element, states);
    }
    for (const attribute of translatedAttributes) {
      const current = element.getAttribute(attribute);
      if (!current) continue;
      const previous = states.get(attribute);
      const source = previous && current === previous.translated ? previous.source : current;
      const translated = translateInterfaceText(source, language);
      states.set(attribute, { source, translated });
      if (current !== translated) element.setAttribute(attribute, translated);
    }
  };

  const translateTree = (node: Node) => {
    if (node.nodeType === Node.TEXT_NODE) {
      translateTextNode(node as Text);
      return;
    }
    if (!(node instanceof Element)) return;
    translateElementAttributes(node);
    const walker = document.createTreeWalker(node, NodeFilter.SHOW_TEXT | NodeFilter.SHOW_ELEMENT);
    let current = walker.nextNode();
    while (current) {
      if (current.nodeType === Node.TEXT_NODE) translateTextNode(current as Text);
      else translateElementAttributes(current as Element);
      current = walker.nextNode();
    }
  };

  translateTree(root);
  const observer = new MutationObserver((mutations) => {
    for (const mutation of mutations) {
      if (mutation.type === "characterData") translateTree(mutation.target);
      for (const node of mutation.addedNodes) translateTree(node);
      if (mutation.type === "attributes") translateElementAttributes(mutation.target as Element);
    }
  });
  observer.observe(root, { subtree: true, childList: true, characterData: true, attributes: true, attributeFilter: [...translatedAttributes] });

  return () => {
    observer.disconnect();
    for (const [node, state] of textState) {
      if (node.isConnected && node.nodeValue === state.translated) node.nodeValue = state.source;
    }
    for (const [element, states] of attributeState) {
      if (!element.isConnected) continue;
      for (const [attribute, state] of states) {
        if (element.getAttribute(attribute) === state.translated) element.setAttribute(attribute, state.source);
      }
    }
  };
}
